// Generates src/styles/prime-theme.css: PrimeReact's Lara theme recoloured to
// the app's plum / warm-stone palette and set in the app's fonts. The Lara
// theme writes its colours as fixed hex values, so they are replaced here.
// Runs automatically before `dev` and `build`; the output is not committed.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(root, "node_modules/primereact/resources/themes/lara-light-purple/theme.css");
const target = resolve(root, "src/styles/prime-theme.css");

const colours = {
  // violet -> plum
  "#f5f3ff": "#f7f4f9", "#ede9fe": "#efe9f3", "#ddd6fe": "#ddd1e5", "#c4b5fd": "#c4b1d1",
  "#a78bfa": "#a48bb6", "#8b5cf6": "#4b3a5a", "#7c3aed": "#3c2e49", "#6d28d9": "#4b3a5a",
  "#5b21b6": "#2e2338", "#4c1d95": "#1e1625",
  // cool grey -> warm stone
  "#f9fafb": "#faf8f5", "#f3f4f6": "#f3efea", "#e5e7eb": "#e7e2dc", "#d1d5db": "#d6cfc6",
  "#9ca3af": "#a39b92", "#6b7280": "#6f685f", "#4b5563": "#322e2a", "#374151": "#1f1d1b",
  "#1f2937": "#1f1d1b", "#111827": "#12110f",
};

let css = readFileSync(source, "utf8");
for (const [from, to] of Object.entries(colours)) {
  css = css.replace(new RegExp(from, "gi"), to);
}
css = css
  .replace(/rgba\(139,\s*92,\s*246,/g, "rgba(75, 58, 90,")
  .replace(/"Inter var", sans-serif/g, '"Source Sans 3 Variable", system-ui, sans-serif')
  // Inter-specific character variants; the custom property first, then the plain one.
  .replace(/--font-feature-settings: "cv02", "cv03", "cv04", "cv11";/g, "")
  .replace(/(?<!-)font-feature-settings: "cv02", "cv03", "cv04", "cv11";/g, "");

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `/* Generated by scripts/prime-theme.mjs from PrimeReact lara-light-purple. Do not edit. */\n${css}`);
console.log(`prime-theme.css written (${Math.round(css.length / 1024)} KB)`);
